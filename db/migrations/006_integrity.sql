ALTER TABLE announcements ADD COLUMN IF NOT EXISTS audience_role TEXT CHECK(audience_role IN ('student','teacher','admin'));
ALTER TABLE announcements ADD COLUMN IF NOT EXISTS program_id BIGINT REFERENCES programs;
CREATE TABLE IF NOT EXISTS attendance_history(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, attendance_id BIGINT NOT NULL REFERENCES attendance, actor_id BIGINT REFERENCES users, before_value JSONB, after_value JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE OR REPLACE FUNCTION audit_attendance_change() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO attendance_history(attendance_id,actor_id,before_value,after_value) VALUES(NEW.id,nullif(current_setting('app.actor_id',true),'')::bigint,CASE WHEN TG_OP='UPDATE' THEN to_jsonb(OLD) ELSE NULL END,to_jsonb(NEW));
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS attendance_change ON attendance;
CREATE TRIGGER attendance_change AFTER INSERT OR UPDATE ON attendance FOR EACH ROW EXECUTE FUNCTION audit_attendance_change();
COMMIT;
